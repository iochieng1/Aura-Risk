export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, sw };

export type MessageParams = Record<string, string | number>;

/** The message for `key` in `lang`, with {placeholders} filled from `params`. */
export function translate(lang: Lang, key: MessageKey, params?: MessageParams): string {
  const template = MESSAGES[lang]?.[key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function isLang(value: unknown): value is Lang {
  return value === 'en' || value === 'sw';
}

/**
 * The first supported language among BCP 47 tags in preference order (e.g.
 * navigator.languages), matched on the primary subtag. Defaults to English.
 */
export function pickLanguage(candidates: readonly string[]): Lang {
  for (const tag of candidates) {
    const primary = tag.trim().toLowerCase().split(/[-_]/)[0];
    if (isLang(primary)) return primary;
  }
  return 'en';
}

export const riskLevelLabel = (lang: Lang, level: RiskLevel): string => translate(lang, `level.${level}`);

export const categoryLabel = (lang: Lang, category: ReportCategory | string): string =>
  `category.${category}` in en ? translate(lang, `category.${category}` as MessageKey) : category;

export const responseStatusLabel = (lang: Lang, status: ResponseStatus): string =>
  translate(lang, `response.${status}`);
